#!/usr/bin/env python3
"""Validate the registers and render them as Markdown views.

    python3 render_views.py [--project DIR]          validate, then write the views folder
    python3 render_views.py [--project DIR] --check  validate and compare with the views on disk; write nothing

Exit codes: 0 registers valid (and views current with --check), 1 validation errors or stale views, 2 usage or a register in the config without `file`, `view` or `fields`.
A view whose register file is gone is reported by --check and deleted when writing.
Vocabularies, date fields, statuses, the priority order and all paths come from pmo/config.yaml
merged over the skill defaults. A register whose file is missing counts as empty and gets no view.
"""
import argparse
import datetime
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pmo_common as pc  # noqa: E402

HEADER = "<!-- GENERATED by render_views.py from {f}. Do not edit; edit the register. -->\n\n"
CATALOGUE_HEADER = "<!-- GENERATED by render_views.py from pmo/config.yaml (doc_types). Do not edit; edit doc_types in pmo/config.yaml. -->\n\n"


def real_date(v):
    if isinstance(v, datetime.date):
        return True
    try:
        return bool(re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(v))) and bool(datetime.date.fromisoformat(str(v)))
    except ValueError:
        return False


def one_line_entries(text):
    """True when every entry sits on one line: after the single top `name:` key line, every line is a `- ` entry (or blank/comment)."""
    lines = [ln for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    return all(re.match(r"\s*- ", ln) for ln in lines[1:])


def config_errors(cfg, root=None):
    """Registers in the config that lack `file`, `view` or `fields`, bad week_start, or invalid blocked/active statuses."""
    errors = [f"config: register `{n}` needs `{k}`" for n, r in cfg["registers"].items() for k in ("file", "view", "fields")
              if not isinstance(r, dict) or not r.get(k)]
    ws = cfg.get("project", {}).get("week_start") if isinstance(cfg.get("project"), dict) else None
    if ws is not None and (not isinstance(ws, str) or ws.lower() not in pc.WEEKDAYS):
        errors.append(f"config: project.week_start `{ws}` not in {list(pc.WEEKDAYS)}")
    task_statuses = cfg.get("vocab", {}).get("task_status") or []
    for key in ("blocked", "active"):
        for s in pc.statuses(cfg, "tasks", key):
            if task_statuses and s not in task_statuses:
                errors.append(f"config: registers.tasks.{key} status `{s}` not in vocab.task_status")
    change_statuses = cfg.get("vocab", {}).get("change_status") or []
    for s in pc.statuses(cfg, "changes", "accepted"):
        if change_statuses and s not in change_statuses:
            errors.append(f"config: registers.changes.accepted status `{s}` not in vocab.change_status")
    pub = cfg.get("publish")
    if pub is not None:
        if isinstance(pub, dict):
            mode = pub.get("mode")
            if mode is not None and mode not in ("none", "folder", "repo"):
                errors.append(f"config: publish.mode `{mode}` must be one of none, folder, repo")
        else:
            errors.append("config: publish must be a map")
    for dt, info in (cfg.get("doc_types") or {}).items():
        if isinstance(info, dict):
            for k in ("when", "regenerate"):
                v = info.get(k)
                if v is not None and not isinstance(v, str):
                    errors.append(f"config: doc_types.{dt}.{k} must be text")

    langs = cfg.get("languages")
    if langs is not None:
        if not isinstance(langs, dict):
            errors.append("config: languages must be a map")
        else:
            draft = langs.get("draft")
            if "draft" in langs:
                if not isinstance(draft, str):
                    errors.append(f"config: languages.draft `{draft}` must be text (quote it if YAML parsed it as a boolean)")
                elif not pc.LANG_CODE.fullmatch(draft):
                    errors.append(f"config: languages.draft `{draft}` must match {pc.LANG_CODE.pattern}")

            trans = langs.get("translations")
            if "translations" in langs:
                if not isinstance(trans, list):
                    errors.append("config: languages.translations must be a list")
                else:
                    seen_trans = set()
                    for t in trans:
                        if not isinstance(t, str):
                            errors.append(f"config: languages.translations entry `{t}` must be text (quote it if YAML parsed it as a boolean)")
                        elif not pc.LANG_CODE.fullmatch(t):
                            errors.append(f"config: languages.translations entry `{t}` must match {pc.LANG_CODE.pattern}")
                        elif isinstance(draft, str) and t == draft:
                            errors.append(f"config: languages.translations code `{t}` cannot be the draft language")
                        elif t in seen_trans:
                            errors.append(f"config: duplicate code `{t}` in languages.translations")
                        else:
                            seen_trans.add(t)

            codes_to_check = set()
            if isinstance(draft, str) and pc.LANG_CODE.fullmatch(draft):
                codes_to_check.add(draft)
            if isinstance(trans, list):
                for t in trans:
                    if isinstance(t, str) and pc.LANG_CODE.fullmatch(t):
                        codes_to_check.add(t)

            for code in sorted(codes_to_check):
                block = langs.get(code)
                if not isinstance(block, dict):
                    errors.append(f"config: languages.{code} must be a map with label and dir")
                else:
                    label = block.get("label")
                    if not isinstance(label, str) or not label.strip():
                        errors.append(f"config: languages.{code}.label must be a non-empty string")
                    d = block.get("dir")
                    if d not in ("ltr", "rtl"):
                        errors.append(f"config: languages.{code}.dir `{d}` must be ltr or rtl")

            for code, block in langs.items():
                if code in ("draft", "translations") or not isinstance(block, dict):
                    continue
                if "glossary" in block:
                    g = block.get("glossary")
                    if not isinstance(g, str) or not g.endswith(".md"):
                        errors.append(f"config: languages.{code}.glossary `{g}` must be a string ending in .md")
                    elif root is not None and pc.outside(root, g):
                        errors.append(f"config: languages.{code}.glossary `{g}` must stay inside the project")
                if "digits" in block:
                    digs = block.get("digits")
                    if not isinstance(digs, str) or len(digs) != 10 or len(set(digs)) != 10:
                        errors.append(f"config: languages.{code}.digits `{digs}` must be a string of ten distinct characters")
                if "connectors" in block:
                    conn = block.get("connectors")
                    if not isinstance(conn, dict):
                        errors.append(f"config: languages.{code}.connectors must be a map")
                    else:
                        allowed_keys = {"of", "to", "and"}
                        for ck, cv in conn.items():
                            if ck not in allowed_keys:
                                errors.append(f"config: languages.{code}.connectors key `{ck}` must be one of {sorted(allowed_keys)}")
                            elif not isinstance(cv, str) or not cv.strip():
                                errors.append(f"config: languages.{code}.connectors.{ck} must be a non-empty string")
                if "separators" in block:
                    sep = block.get("separators")
                    if not isinstance(sep, str):
                        errors.append(f"config: languages.{code}.separators must be text")

    proj_trans = set()
    if isinstance(langs, dict) and isinstance(langs.get("translations"), list):
        proj_trans = {t for t in langs["translations"] if isinstance(t, str)}

    for dt, info in (cfg.get("doc_types") or {}).items():
        if isinstance(info, dict):
            if "translate" in info:
                tr = info.get("translate")
                if tr not in ("in-period", "after-close"):
                    errors.append(f"config: doc_types.{dt}.translate `{tr}` must be in-period or after-close")
            if "translations" in info:
                dtrans = info.get("translations")
                if not isinstance(dtrans, list):
                    errors.append(f"config: doc_types.{dt}.translations must be a list")
                else:
                    for c in dtrans:
                        if not isinstance(c, str) or c not in proj_trans:
                            errors.append(f"config: doc_types.{dt}.translations code `{c}` not in languages.translations")

    return errors


def read_registers(root, cfg):
    """({name: entries}, errors) for the registers that exist."""
    data, errors = {}, []
    for name, reg in cfg["registers"].items():
        f = Path(root) / cfg["paths"]["registers"] / reg["file"]
        if not f.exists():
            continue
        text = pc.read(f)
        try:
            entries = (pc.yaml.safe_load(text) or {}).get(name) or []
        except (pc.yaml.YAMLError, AttributeError, ValueError) as e:  # ValueError: a date like 2026-02-30
            errors.append(f"{reg['file']}: not readable as `{name}:` followed by a list ({str(e).splitlines()[0]})")
            continue
        if not isinstance(entries, list) or not all(isinstance(e, dict) for e in entries):
            errors.append(f"{reg['file']}: `{name}` must be a list of entries (maps)")
        elif not one_line_entries(text):
            errors.append(f"{reg['file']}: every entry must be on one line (`- {{id: ..., title: ...}}`)")
        else:
            data[name] = entries
    return data, errors


def validate(data, cfg):
    errors, seen = [], {}
    vocab = cfg["vocab"]
    slugs = {r.get("slug") for r in data.get("roster", [])}
    for name, rows in data.items():
        reg = cfg["registers"][name]
        allowed, prefix = set(reg["fields"]), reg.get("prefix")
        for i, r in enumerate(rows, 1):
            rid = r.get("id")
            who = f"{name} {rid if rid else '#%d' % i}"
            for k in r:
                if k not in allowed and not str(k).startswith("x_"):
                    errors.append(f"{who}: unexpected field '{k}' (an unquoted comma in a value? allowed: {sorted(allowed)})")
            if "id" in allowed:
                if not rid:
                    errors.append(f"{who}: missing id")
                elif not isinstance(rid, str):
                    errors.append(f"{who}: id {rid!r} must be text (quote it)")
                elif rid in seen:
                    errors.append(f"duplicate id {rid} ({name} and {seen[rid]})")
                else:
                    seen[rid] = name
                if rid and isinstance(rid, str) and prefix and not re.fullmatch(re.escape(prefix) + r"-\d+", str(rid)):
                    errors.append(f"{who}: id must look like {prefix}-1")
            for field, vname in reg.get("enums", {}).items():
                values = r.get(field)  # null is allowed (never guess), except for status
                if values is None and field != "status" or not vocab.get(vname):
                    continue
                for v in values if isinstance(values, list) else [values]:
                    if v not in vocab[vname]:
                        errors.append(f"{who}: {field} {v!r} not in {vocab[vname]}")
            for field in reg.get("dates", []):
                if r.get(field) and not real_date(r[field]):
                    errors.append(f"{who}: {field} {r[field]!r} is not a YYYY-MM-DD date")
            owners = r.get("owner")
            for o in owners if isinstance(owners, list) else [owners]:
                if o and slugs - {None} and o not in slugs:
                    errors.append(f"{who}: owner {o!r} is not in the roster")
    return errors


def table(rows, cols):
    if not rows:
        return "_No entries._\n"
    return pc.md_table(cols, [[r.get(c) for c in cols] for r in rows])


def view_tasks(rows, cfg):
    reg = cfg["registers"]["tasks"]
    statuses, closed = cfg["vocab"].get(reg.get("enums", {}).get("status")) or [], reg.get("closed", [])
    n = lambda rs, s: sum(1 for r in rs if r.get("status") == s)
    done = sum(1 for r in rows if r.get("status") in closed)
    counts = ", ".join(f"{s} {n(rows, s)}" for s in statuses)
    out = [f"# Tasks\n\n**Progress:** {done}/{len(rows)} closed ({round(100 * done / len(rows)) if rows else 0}%). {counts}\n"]
    order = cfg["vocab"].get("priority_order") or []
    key = lambda p: (p is None, order.index(p) if p in order else len(order), str(p))
    pri = [{"priority": p or "not set", "total": len(rs := [r for r in rows if r.get("priority") == p]),
            **{s: n(rs, s) for s in statuses}} for p in sorted({r.get("priority") for r in rows}, key=key)]
    out += ["## By priority\n", table(pri, ["priority", "total", *statuses]), "## By team and group\n"]
    for team in sorted({r.get("team") or "" for r in rows}, key=str):
        out.append(f"### {team or 'no team'}\n")
        for g in sorted({r.get("group") or "" for r in rows if (r.get("team") or "") == team}, key=str):
            out.append(f"**{g or 'no group'}**\n")
            sub = [r for r in rows if (r.get("team") or "") == team and (r.get("group") or "") == g]
            sub.sort(key=lambda r: key(r.get("priority")))
            out.append(table(sub, ["id", "title", "priority", "owner", "status", "due"]))
    return "\n".join(out)


def render(data, cfg):
    """{view file name: text}, in config order."""
    views = {}
    for name, rows in data.items():
        reg = cfg["registers"][name]
        body = view_tasks(rows, cfg) if name == "tasks" else f"# {name.capitalize()}\n\n" + table(rows, reg["fields"])
        views[reg["view"]] = HEADER.format(f=f"{cfg['paths']['registers']}/{reg['file']}") + body
    cat_headers = ["Doc type", "Title", "Made by", "When", "Regenerate", "Stale after", "Published"]
    cat_rows = []
    for dt, info in (cfg.get("doc_types") or {}).items():
        if not isinstance(info, dict):
            continue
        title = info.get("title") or "not set"
        made_by = "generator" if info.get("generator") is True else "agent"
        when = str(info.get("when")) if info.get("when") else "not set"
        regen = str(info.get("regenerate")) if info.get("regenerate") else "not set"
        stale = f"{info['stale_days']} days" if info.get("stale_days") is not None else "not set"
        pub = "no" if info.get("publish") is False else "yes"
        cat_rows.append([dt, title, made_by, when, regen, stale, pub])
    cat_body = "# Catalogue\n\n" + pc.md_table(cat_headers, cat_rows)
    views["catalogue.md"] = CATALOGUE_HEADER + cat_body
    return views


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    pc.add_project_arg(ap)
    ap.add_argument("--check", action="store_true", help="validate and compare with the views on disk; write nothing")
    args = ap.parse_args(argv)
    if not Path(args.project).is_dir():
        ap.error(f"project folder not found: {args.project}")
    cfg = pc.load_config(args.project)
    if bad := config_errors(cfg, root=args.project):
        print("\n".join("ERROR " + e for e in bad))
        return 2
    data, errors = read_registers(args.project, cfg)
    errors += validate(data, cfg)
    views = render(data, cfg)
    folder = Path(args.project) / cfg["paths"]["views"]
    # a view whose register file is gone is left over
    orphans = [r["view"] for r in cfg["registers"].values() if r["view"] not in views and (folder / r["view"]).exists()]
    if args.check and not errors:
        errors = [f"stale view: {cfg['paths']['views']}/{n}" for n, t in views.items()
                  if not (folder / n).exists() or pc.read(folder / n) != t]
        errors += [f"stale view: {cfg['paths']['views']}/{n} (register file is gone)" for n in orphans]
    for e in errors:
        print("ERROR", e)
    if errors:
        return 1
    if args.check:
        print("registers valid, views current")
        return 0
    folder.mkdir(parents=True, exist_ok=True)
    for n, t in views.items():
        pc.write(folder / n, t)
    for n in orphans:
        (folder / n).unlink()
    print(f"registers valid; wrote {len(views)} views to {cfg['paths']['views']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
